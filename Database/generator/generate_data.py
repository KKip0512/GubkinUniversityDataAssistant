def sql_value(v):
    if v is None:
        return "NULL"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, dt.date):
        return f"'{v.isoformat()}'"
    return "'" + str(v).replace("'", "''") + "'"


def write_table(table, columns, rows, batch=1000):
    path = OUT_DIR / f"{table}_rows.sql"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        for start in range(0, len(rows), batch):
            f.write(f"INSERT INTO public.{table} ({', '.join(columns)}) VALUES\n")
            f.write(",\n".join("(" + ", ".join(sql_value(v) for v in row) + ")"
                               for row in rows[start:start + batch]))
            f.write(";\n")
    print(f"{path.name:<28} {len(rows):>7} строк")


