def hours(title, control, level):
    if title in NO_LECTURES:
        return 0, 54 if control == EXAM else 36
    if level == POSTGRAD:
        return 18, 18
    return (36, 36) if control == EXAM else (18, 18)


def add_plan(pid, faculty_id, level, plan):
    for sem in sorted(plan):
        for title, control in plan[sem]:
            lec, sem_h = hours(title, control, level)
            curriculum[pid].append((sem, subject_id(title, faculty_id), control, lec, sem_h))


def build_plan(general, spec_titles, spec_slots):
    """Общие дисциплины + профильные, разложенные по семестрам по порядку."""
    plan = {sem: list(items) for sem, items in general.items()}
    it = iter(spec_titles)
    for sem, count in spec_slots.items():
        for k in range(count):
            plan[sem].append((next(it), EXAM if k % 2 == 0 else CREDIT))
    return plan


