def split_groups(n, target, maximum):
    k = max(1, round(n / target))
    while n / k > maximum:
        k += 1
    return largest_remainder(n, [1] * k)


def chunk(seq, size):
    k = math.ceil(len(seq) / size)
    sizes = largest_remainder(len(seq), [1] * k)
    out, pos = [], 0
    for s in sizes:
        out.append(seq[pos:pos + s])
        pos += s
    return out


